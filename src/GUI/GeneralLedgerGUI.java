    private final Color selectedColor = new Color(36, 112, 190);

    private JButton selectedButton;

    private void setupSidebar() {

        JButton[] buttons = {
            btnDashBoard,
            btnChartOfAcct,
            btnTransaction,
            btnInventory,
            btnGeneralLedger,
            btnGeneralJournal,
            btnReports,
            btnAbout
        };

        for (JButton button : buttons) {

            button.setBackground(normalColor);
            button.setForeground(Color.WHITE);
            button.setFocusPainted(false);
            button.setBorderPainted(false);
            button.setContentAreaFilled(true);
            button.setOpaque(true);

            button.addMouseListener(new java.awt.event.MouseAdapter() {

                @Override
                public void mouseEntered(java.awt.event.MouseEvent e) {
                    if (button != selectedButton) {
                        button.setBackground(hoverColor);
                    }
                }

                @Override
                public void mouseExited(java.awt.event.MouseEvent e) {
                    if (button != selectedButton) {
                        button.setBackground(normalColor);
                    }
                }
            });

            button.addActionListener(e -> selectButton(button));
        }

        selectButton(btnDashBoard);
    }

    private void selectButton(JButton button) {

        if (selectedButton != null) {
            selectedButton.setBackground(normalColor);
        }

        selectedButton = button;
        selectedButton.setBackground(selectedColor);
}

